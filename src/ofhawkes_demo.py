"""Demo run for the compound Hawkes order-flow engine.

Generates 5 synthetic Hawkes days plus 1 Poisson control day, computes
descriptive statistics, and writes demo_data.json for the dashboard.
SYNTHETIC DATA ONLY: no programme dataset is touched, nothing is
measured for any claim, and no kill line is involved.
"""
import json
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ofhawkes import (  # noqa: E402
    DIM_NAMES, NDIM, abs_returns_acf, build_config, interarrival_histograms,
    signature_plot, simulate_day, simulate_poisson_day, size_histograms,
    spectral_radius,
)

OUT = Path.cwd() / "ofhawkes_demo_data.json"  # do not commit; .gitignored
NDAYS = 5


def main() -> None:
    t0 = time.time()
    cfg, disc = build_config(seed=20261118, target_rho=0.5)
    cfg.amp = cfg.amp * 0.5     # moderate excitation for a stable, honest demo
    cfg.mu = cfg.mu * 0.85
    cfg.dt = 0.02

    days = []
    for k in range(NDAYS):
        d = simulate_day(cfg, day_index=k)
        days.append(d)
        print(f"day {k}: {len(d.events_t)} events, peak lam "
              f"{d.peak_intensity:.1f}, med spread {int(np.median(d.spread))}", flush=True)

    pois = simulate_poisson_day(cfg, day_index=0)
    print(f"poisson control: {len(pois.events_t)} events", flush=True)

    M = cfg.norm_matrix()
    rho = spectral_radius(M)

    # --- mid price per day concatenated at 1s ---
    mid_all = np.concatenate([d.mid for d in days])
    day_ids = []
    off = 0
    for d in days:
        day_ids.append(np.arange(off, off + len(d.mid)))
        off += len(d.mid)

    scales, vol_h = signature_plot(mid_all, day_ids)
    # poisson signature uses its own day
    scales_p, vol_p = signature_plot(pois.mid, [np.arange(len(pois.mid))])
    acf_h = abs_returns_acf(days[0].mid)
    acf_p = abs_returns_acf(pois.mid)

    inter = interarrival_histograms(days[0], dims=(4, 2, 5), n_bins=48)
    inter_p = interarrival_histograms(pois, dims=(4,), n_bins=48)

    sizes = size_histograms(days, {"MO": (4, 9), "LO top": (2, 7), "CO top": (3, 8)})

    # spread distribution day 0
    spread_vals = days[0].spread
    spread_hist = [int((spread_vals == s).sum()) for s in range(1, 11)]

    # event counts per dim per 30s bin, day 0 (12 dims x 780 bins)
    HORIZON = int(days[0].events_t.max() // 1 or 23400)
    nev = np.zeros((NDIM, 780), dtype=int)
    t = days[0].events_t
    dm = days[0].events_dim
    idx = np.minimum((np.asarray(t) // 30).astype(int), 779)
    np.add.at(nev, (np.asarray(dm), idx), 1)

    # intensity decomposition, day 0 (30s cadence already in DayResult)
    endog_share = days[0].endog_share

    total_per_dim = [int((np.concatenate([d.events_dim for d in days]) == i).sum()) for i in range(NDIM)]

    demo = {
        "meta": {
            "engine": "compound Hawkes order-flow engine (12D)",
            "model_note": (
                "Synthetic demonstration after Jain et al., arXiv:2312.08927v5. "
                "All data generated by this engine. Not market data. No programme "
                "dataset touched. No claim is made or tested. No kill line involved."
            ),
            "dim_names": list(DIM_NAMES),
            "dt": cfg.dt,
            "ndays": NDAYS,
            "events_total": int(sum(len(d.events_t) for d in days)),
            "events_poisson": int(len(pois.events_t)),
            "rho_M": float(rho),
            "threshold": float(disc.threshold),
            "stability_disclosure": disc.as_dict(),
            "endog_share_gross": float(1 - sum(d.gross_exog for d in days) / sum(d.gross_total for d in days)),
            "endog_share_poisson": float(1 - pois.gross_exog / pois.gross_total),
            "spread_median_day0": float(np.median(days[0].spread)),
            "mid_range_day0_ticks": float((days[0].mid.max() - days[0].mid.min()) / 2.0),
            "sizes_mean": {k: v["mean"] for k, v in sizes.items()},
        },
        "day0": {
            "mid": days[0].mid.tolist(),          # half-ticks per second
            "spread": days[0].spread.tolist(),
            "book_t": days[0].book_t.tolist(),
            "q_ask_top": days[0].q_ask_top.tolist(),
            "q_ask_deep": days[0].q_ask_deep.tolist(),
            "q_bid_top": days[0].q_bid_top.tolist(),
            "q_bid_deep": days[0].q_bid_deep.tolist(),
            "event_bins_30s": nev.tolist(),       # [dim][bin]
            "endog_share_30s": endog_share.tolist(),
        },
        "signature": {"scales": scales, "hawkes": vol_h, "poisson": vol_p},
        "acf": {"hawkes": acf_h.tolist(), "poisson": acf_p.tolist()},
        "interarrival": {
            "hawkes": {str(k): v for k, v in inter.items()},
            "poisson": {str(k): v for k, v in inter_p.items()},
        },
        "sizes": sizes,
        "spread_hist": spread_hist,
        "total_per_dim": total_per_dim,
        "norm_matrix": M.tolist(),
        "tod": cfg.tod.tolist(),
    }
    OUT.write_text(json.dumps(demo, separators=(",", ":")))
    print(f"wrote {OUT} ({OUT.stat().st_size/1e6:.2f} MB) in {time.time()-t0:.1f}s total")
    print("endog share (gross):", demo["meta"]["endog_share_gross"])
    print("poisson endog share (must be ~0):", demo["meta"]["endog_share_poisson"])
    print("total events:", demo["meta"]["events_total"],
          "vs poisson day0:", demo["meta"]["events_poisson"])


if __name__ == "__main__":
    main()
